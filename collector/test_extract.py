"""extract.blame 시험: 빠른 길(한 번만 추가된 파일·본인 commit이 닿지 않은 파일은 blame 없이 줄만 셈)이 모든 파일을 blame하던 결과와 같은지 본다.

네트워크를 쓰지 않는다. 레포는 임시 폴더에 만든다.
"""
import re
import subprocess
import tempfile
import unittest
from unittest import mock

import extract
import paths
from testkit import EMAILS, MATE, ME, NAMES, TWIN, FakeApi, Repo, lines


def blame_reference(path, sha, emails, names):
    """정답 기준: 경로·내용 필터(paths.skipped·generated)를 거친 모든 파일을 blame한다. git 출력은 바이트로 읽고, 줄은 git이 내준 줄 번호 그대로 센다."""
    count, units = dict(own=0, name_only=0, other=0, files=0), []
    for entry in extract.git(path, 'ls-tree', '-r', '-l', '-z', sha).split('\0'):
        if not entry: continue
        meta, p = entry.split('\t', 1)
        _, kind, blob, size = meta.split()
        if kind != 'blob' or paths.skipped(p, int(size)): continue
        head = subprocess.run(['git', '-C', str(path), 'cat-file', 'blob', blob], capture_output=True, check=True).stdout[:paths.HEAD_BYTES]
        if paths.generated(p, head): continue
        r = subprocess.run(['git', '-C', str(path), 'blame', '-w', '--line-porcelain', sha, '--', p], capture_output=True)
        if r.returncode: continue
        count['files'] += 1
        mine, by_line, mail, author, line = [], {}, None, None, None
        for row in r.stdout.split(b'\n'):
            if re.match(rb'[0-9a-f]{40,64} \d+ \d+', row): line = int(row.split()[2])
            elif row.startswith(b'author-mail '): mail = row[13:-1].decode('utf-8', 'replace').lower()
            elif row.startswith(b'author '): author = row[7:].decode('utf-8', 'replace')
            elif row.startswith(b'\t'): by_line[line] = (mail, author)
        for n, (mail, author) in sorted(by_line.items()):
            if mail in emails: count['own'] += 1; mine.append(n)
            elif author in names: count['name_only'] += 1
            else: count['other'] += 1
        if mine: units.append(dict(sha=sha, path=p, lines=extract.ranges(mine)))
    return count, units


class Paths(unittest.TestCase):
    def test_build_and_generated_files_are_skipped(self):
        self.assertTrue(paths.skipped('bin/Debug/app.exe', 10))
        self.assertTrue(paths.skipped('x/lib.dll', 10) and paths.skipped('a.pdb', 1) and paths.skipped('m.o', 1))
        self.assertTrue(paths.skipped('venv-win/Lib/site-packages/requests/api.py', 10))
        self.assertFalse(paths.skipped('src/app.py', 10))
        self.assertTrue(paths.generated('dist/a.js', b'x' * 5000 + b'\n'))  # 한 줄이 아주 긴 minified
        self.assertTrue(paths.generated('db/dump.sql', b'INSERT INTO t VALUES (1);\n' * 60))
        self.assertFalse(paths.generated('db/schema.sql', b'CREATE TABLE t (id int);\n' * 60))
        self.assertTrue(paths.generated('gen/x.py', b'# @generated by protoc\nx = 1\n'))

    def test_skipped_covers_build_outputs_and_dependency_folders(self):
        for p in ('lib/a.dylib', 'x/a.obj', 'x/a.so', 'x/a.a', 'x/a.lib', 'x/a.wasm', 'pkg/m.pyc', 'bin/APP.EXE', 'pip/_vendor/requests/api.py',
                  'env/lib/python3.12/site-packages/x.py', 'package-lock.json', 'node_modules/x/index.js', 'static/app.min.js'):
            self.assertTrue(paths.skipped(p, 10), p)
        for p in ('src/exe/run.py', 'src/lib/util.py', 'src/my_vendor/x.py', 'src/site_packages_notes.md', 'docs/data.alpha', 'main.c', 'src/solid.py'):
            self.assertFalse(paths.skipped(p, 10), p)
        self.assertFalse(paths.skipped('big.txt', paths.MAX_BLOB))
        self.assertTrue(paths.skipped('big.txt', paths.MAX_BLOB + 1))

    def test_long_line_rule_boundary_and_exemptions(self):
        line = b'x' * 299 + b'\n'  # 줄바꿈 포함 300바이트
        self.assertFalse(paths.generated('a.js', line * 2))  # 평균 300 → 아님(300을 넘어야 한다)
        self.assertTrue(paths.generated('a.js', line + b'x' * 300 + b'\n'))  # 평균 300.5
        self.assertFalse(paths.generated('a.js', b'x' * 300))  # 줄바꿈 없는 한 줄도 한 줄로 센다
        self.assertTrue(paths.generated('a.js', b'x' * 301))
        self.assertFalse(paths.generated('a.js', b''))  # 빈 파일
        for name in ('book.md', 'A.MD', 'n.markdown', 'doc.rst', 'notes.txt', 'lab.ipynb', 'Lab.IPYNB'):
            self.assertFalse(paths.generated(name, b'x' * 5000 + b'\n'), name)  # 노트북(base64 출력)·문서(한글은 한 글자 3바이트)는 긴 줄이 정상
        for name in ('data.json', 'page.html', 'README'):
            self.assertTrue(paths.generated(name, b'x' * 5000 + b'\n'), name)

    def test_long_line_rule_counts_bytes(self):  # 글자 수가 아니라 바이트: 보수적인 쪽이고, 캐시 7만 파일에서 판정이 달라지는 파일이 없었다
        korean = ('가' * 130).encode() + b'\n'  # 130글자, 391바이트
        self.assertEqual(len(korean), 391)
        self.assertTrue(paths.generated('page.html', korean * 30))

    def test_nul_byte_in_first_8000_bytes_means_binary(self):  # git의 바이너리 판별과 같다. 확장자와 상관없이 적용
        self.assertTrue(paths.generated('model.tflite', b'\x00abc\n' * 3))
        self.assertTrue(paths.generated('out.txt', 'hello\nworld\n'.encode('utf-16')))  # UTF-16 텍스트
        inside, outside = b'a\n' * 3999 + b'a\x00', b'a\n' * 4000 + b'\x00\n'
        self.assertEqual((inside.index(b'\x00'), outside.index(b'\x00')), (7999, 8000))
        self.assertTrue(paths.generated('a.dat', inside))  # 인덱스 7999: 앞 8000바이트 안
        self.assertFalse(paths.generated('a.dat', outside))  # 인덱스 8000: 이 규칙이 아니다

    def test_sql_dump_tool_markers_in_first_5_lines(self):  # 덤프 도구가 머리말에 남기는 표지. 본문이 짧은 줄뿐이라 다른 규칙으로는 안 걸린다
        mysql_body = (b'DROP TABLE IF EXISTS `users`;\nCREATE TABLE `users` (\n  `id` int NOT NULL,\n  `name` varchar(50) DEFAULT NULL\n'
                      b') ENGINE=InnoDB;\nLOCK TABLES `users` WRITE;\nUNLOCK TABLES;\n')
        pg_body = b'SET statement_timeout = 0;\nCREATE TABLE public.t (\n    id integer NOT NULL\n);\nCOPY public.t (id) FROM stdin;\n1\n2\n3\n\\.\n'
        host = b'--\n-- Host: localhost    Database: shop\n--\n\n'
        dumps = {
            b'-- MySQL dump': b'-- MySQL dump 10.13  Distrib 8.0.33, for Linux (x86_64)\n' + host + mysql_body,
            b'-- MariaDB dump': b'-- MariaDB dump 10.19  Distrib 10.11.2-MariaDB, for debian-linux-gnu (x86_64)\n' + host + mysql_body,
            b'-- PostgreSQL database dump': b'--\n-- PostgreSQL database dump\n--\n\n-- Dumped from database version 15.3\n-- Dumped by pg_dump version 15.3\n\n' + pg_body,
            b'-- phpMyAdmin SQL Dump': b'-- phpMyAdmin SQL Dump\n-- version 5.2.1\n-- https://www.phpmyadmin.net/\n' + host + mysql_body,
        }
        for marker, dump in dumps.items():
            self.assertTrue(paths.generated('dump.sql', dump), marker)
            self.assertFalse(paths.generated('dump.sql', dump.replace(marker, b'-- note')), marker)  # 표지만 빼면 다른 규칙으로는 안 걸린다
        self.assertFalse(paths.generated('dump.sql', b'-- x\n' * 5 + b'-- MySQL dump 10.13\n' + mysql_body))  # 6번째 줄
        self.assertFalse(paths.generated('dump.sql', b'-- mysql dump 10.13\n' + mysql_body))  # 대소문자를 구분한다

    def test_line_count_helper_and_passed_in_count(self):  # 줄 수 = 줄바꿈 수 + 줄바꿈 없이 끝나는 마지막 줄. 센 값을 넘기면 다시 세지 않는다
        for body, want in ((b'', 0), (b'\n', 1), (b'a', 1), (b'a\n', 1), (b'a\nb', 2), (b'a\n\nb\n', 3), (b'a\r\tb\n', 1)):
            self.assertEqual(paths.line_count(body), want, body)
        for head in (b'x' * 301, (b'x' * 299 + b'\n') * 2, (b'x' * 299 + b'\n') * 2 + b'y', b'INSERT INTO t VALUES (1);\n' * 60):
            self.assertEqual(paths.generated('a.js', head, paths.line_count(head)), paths.generated('a.js', head))
        self.assertTrue(paths.generated('a.js', b'x' * 301, 1))
        self.assertFalse(paths.generated('a.js', b'x' * 301, 2))  # 넘긴 값을 그대로 쓴다(2줄이면 평균 150)

    def test_sql_dump_heidisql_export_with_values_rows(self):  # INSERT INTO 한 줄 뒤에 탭으로 들여쓴 (..), 행이 이어지는 내보내기
        header = (b'-- --------------------------------------------------------\n-- Host:                         127.0.0.1\n'
                  b'-- Server version:               8.0.33\n-- Server OS:                    Win64\n-- HeidiSQL Version:             12.5.0.6677\n')
        heidi = header + b'INSERT INTO `t` (`a`, `b`) VALUES\n' + b"\t(1, 'x'),\n" * 200 + b"\t(2, 'y');\n"
        self.assertTrue(paths.generated('export.sql', heidi))
        crlf = b'INSERT INTO t (a) VALUES\r\n' + b'\t(1),   \r\n' * 50 + b'\t(2);\r\n'  # 끝의 공백·탭과 \r까지 허용
        self.assertTrue(paths.generated('export.sql', crlf))
        self.assertFalse(paths.generated('export.sql', heidi.replace(b'INSERT INTO', b'SELECT * FROM')))  # insert into가 없으면 이 규칙은 보지 않는다
        self.assertTrue(paths.generated('export.sql', b'INSERT INTO t (a) VALUES\n\t(1);\n' * 40))  # (..); 로 끝나는 행도 센다: 80줄 중 80줄(이 행을 안 세면 50%)

    def test_sql_dump_with_ddl_needs_50_data_lines(self):  # 테이블 정의가 있으면 데이터 줄이 50줄 이상일 때만 덤프로 본다
        ins, sel = b'INSERT INTO t VALUES (1);\n', b'SELECT * FROM t;\n'
        ddl60 = b'CREATE TABLE t (\n' + b'  col INT,\n' * 58 + b');\n'  # 60줄
        self.assertTrue(paths.generated('db/init.sql', ddl60 + ins * 300))  # 정의 60줄 + 한 줄짜리 INSERT 300줄
        schema = b''.join(b'CREATE TABLE a%d (\n  id int,\n  name text,\n  PRIMARY KEY (id)\n);\n' % k for k in range(3))  # 3개 x 5줄
        self.assertFalse(paths.generated('schema.sql', schema + ins * 23))  # 23/38 = 60.5%여도 49줄 이하라 직접 쓴 schema.sql
        self.assertFalse(paths.generated('schema.sql', schema + ins * 49))  # 49/64 = 76%
        self.assertTrue(paths.generated('schema.sql', schema + ins * 50))  # 50/65 = 77%
        self.assertFalse(paths.generated('schema.sql', schema + ins * 50 + sel * 40))  # 50줄이어도 50/105 = 48%
        for line in (b'CREATE TABLE a (id int);\n', b'  create\ttable a (id int);\n', b'ALTER TABLE a ADD b int;\n'):
            self.assertFalse(paths.generated('x.sql', line + ins * 40), line)
            self.assertTrue(paths.generated('x.sql', line + ins * 50), line)

    def test_sql_dump_without_ddl_has_no_size_floor_and_needs_60_percent(self):
        ins, sel = b'INSERT INTO t VALUES (1);\n', b'SELECT * FROM t;\n'
        self.assertTrue(paths.generated('seed.sql', ins))  # 크기 하한 없음
        self.assertTrue(paths.generated('seed.sql', ins * 10))
        self.assertTrue(paths.generated('seed.sql', ins * 6 + sel * 4))  # 6/10 = 60%
        self.assertFalse(paths.generated('seed.sql', ins * 5 + sel * 5))
        self.assertTrue(paths.generated('seed.sql', ins * 30 + sel * 20))  # 30/50
        self.assertFalse(paths.generated('seed.sql', ins * 29 + sel * 21))  # 29/50 = 58%
        self.assertTrue(paths.generated('seed.sql', ins * 6 + sel * 4 + b'\n' * 30 + b' \t\r\n' * 5))  # 빈 줄·공백뿐인 줄은 세지 않는다
        self.assertTrue(paths.generated('a.sql', b'  insert into t values (1);\n' * 5))  # 앞 공백·소문자
        self.assertTrue(paths.generated('a.sql', b'Insert\t Into t VALUES (1);\n' * 3))  # 대소문자가 섞이고 사이에 공백·탭
        self.assertTrue(paths.generated('a.sql', b'INSERT INTO a\nINSERT INTO b\nfoo'))  # 줄바꿈 없는 마지막 줄도 한 줄: 2/3
        self.assertFalse(paths.generated('a.sql', b'INSERT INTOx t\n' * 10))  # INTO 뒤는 단어 경계
        self.assertTrue(paths.generated('dump.txt', ins * 60))  # 긴 줄 규칙에서 빠지는 확장자라도 이 규칙은 적용한다

    def test_sql_dump_rule_is_skipped_without_insert_into(self):  # 사전 검사: insert into가 앞 64KB에 한 번도 없으면 튜플 줄 모양만으로는 안 본다
        self.assertFalse(paths.generated('data.py', b'    (1, 2),\n' * 100))
        self.assertFalse(paths.generated('data.py', b'    (1, 2);\n' * 100))
        self.assertFalse(paths.generated('data.py', b'insert\n(1, 2),\n' * 100))  # insert만 있고 into가 없다

    def test_marker_rule_looks_only_at_first_5_lines_and_is_case_sensitive(self):
        self.assertTrue(paths.generated('a.py', b'x\n' * 4 + b'# @generated\n'))  # 5번째 줄
        self.assertFalse(paths.generated('a.py', b'x\n' * 5 + b'# @generated\n'))  # 6번째 줄
        self.assertTrue(paths.generated('a.go', b'// Code generated by tool. DO NOT EDIT.\n'))
        self.assertFalse(paths.generated('a.go', b'// do not edit by hand\n'))  # 대소문자를 구분한다
        self.assertFalse(paths.generated('a.py', b'# @Generated\n'))
        self.assertTrue(paths.generated('NOTES.md', b'<!-- DO NOT EDIT -->\n# title\n'))  # 문서도 표지는 본다


class FastBlame(unittest.TestCase):
    def check(self, repo):
        sha = repo.head()
        want = blame_reference(repo.path, sha, EMAILS, NAMES)
        got = extract.blame(repo.path, sha, EMAILS, NAMES)
        self.assertEqual(got[0], want[0])
        self.assertEqual(sorted(got[1], key=lambda u: u['path']), sorted(want[1], key=lambda u: u['path']))
        return got

    def test_scenarios_match_blaming_every_file(self):
        with tempfile.TemporaryDirectory() as d:
            r = Repo(d)
            r.commit(ME, {'mine.py': lines('me', 30), 'shared.py': lines('me', 20), 'renamed_later.py': lines('me', 12),
                          'ws.py': lines('me', 8), 'no_newline.txt': 'a\nb\nlast', 'empty.txt': '', 'gone.py': lines('me', 5),
                          'node_modules/x.js': lines('me', 50), 'logo.png': b'\x89PNG\x00\x01\n\x02'})
            r.commit(MATE, {'mate.py': lines('mate', 40), 'shared.py': lines('me', 10) + lines('mate', 5)})  # 내 파일 일부를 팀원이 고침
            r.commit(MATE, move=[('renamed_later.py', 'pkg/renamed.py')])                 # 팀원이 내 파일을 옮김(내용 그대로)
            r.commit(MATE, {'ws.py': lines('me', 8).replace(' with', '  with')})          # 공백만 바꿈(-w로 내 줄 유지)
            r.commit(MATE, {'mate_then_moved_by_me.py': lines('mate', 9)})
            r.commit(ME, move=[('mate_then_moved_by_me.py', 'moved_by_me.py')])          # 내가 옮긴 팀원 파일: 줄은 팀원 것
            r.commit(ME, delete=['gone.py'])
            r.commit(MATE, {'gone.py': lines('mate', 5)})                                  # 지웠다가 다시 추가
            r.commit(TWIN, {'twin.py': lines('twin', 7)})                                  # 이름만 같은 사람
            r.commit(ME, {'binaryish.dat': b'\x00\x01\x02\n\x03'})
            count, units = self.check(r)
            self.assertGreater(count['own'], 0)
            self.assertEqual(count['name_only'], 7)

    def test_lone_carriage_return_is_not_a_line_break(self):  # git은 \n으로만 줄을 나눈다(빌드 결과 .exe 등에 \r이 섞여 있음)
        with tempfile.TemporaryDirectory() as d:
            r = Repo(d)
            r.commit(ME, {'old_mac.txt': b'a\r\tb\r\tc\n', 'mixed.txt': b'x\ny\r\tz\n'})
            r.commit(MATE, {'mixed.txt': b'x\nY\r\tz\n'})
            count, units = self.check(r)
            self.assertEqual(count['own'] + count['other'], 3)  # old_mac 1줄 + mixed 2줄
            self.assertEqual(sorted((u['path'], u['lines']) for u in units), [('mixed.txt', [[1, 1]]), ('old_mac.txt', [[1, 1]])])

    def test_conflict_resolution_in_my_merge_commit_counts_as_mine(self):
        with tempfile.TemporaryDirectory() as d:
            r = Repo(d)
            r.commit(MATE, {'app.py': lines('base', 6)})
            r.git('checkout', '-q', '-b', 'side')
            r.commit(MATE, {'app.py': lines('side', 6)})
            r.git('checkout', '-q', 'main')
            r.commit(MATE, {'app.py': lines('main', 6)})
            r.git('merge', '-q', 'side', '-m', 'merge', check=False, who=ME)
            (r.path / 'app.py').write_text(lines('resolved', 6))
            r.git('add', 'app.py')
            r.git('commit', '-q', '--no-edit', who=ME)
            count, _ = self.check(r)
            self.assertEqual(count['own'], 6)

    def test_bulk_import_is_counted_without_blaming_each_file(self):  # 커널 소스처럼 한 번에 올린 파일 수천 개
        with tempfile.TemporaryDirectory() as d:
            r = Repo(d)
            r.commit(ME, {f'vendor_src/m{i}.c': lines('k', 3) for i in range(400)})
            r.commit(ME, {'vendor_src/m0.c': lines('k', 2) + lines('me', 4)})
            calls = []
            real = subprocess.run
            def spy(cmd, *args, **kw):
                if 'blame' in cmd: calls.append(cmd[-1])
                return real(cmd, *args, **kw)
            extract.subprocess.run = spy
            try: count, _ = extract.blame(r.path, r.head(), EMAILS, NAMES)
            finally: extract.subprocess.run = real
            self.assertEqual(count, blame_reference(r.path, r.head(), EMAILS, NAMES)[0])
            self.assertEqual(calls, ['vendor_src/m0.c'])  # 두 번 이상 바뀐 파일만 blame한다

    def test_blame_skips_generated_files(self):  # SQL 덤프는 줄 세기에서 빠진다(한 번만 추가된 파일: 빠른 길)
        with tempfile.TemporaryDirectory() as d:
            r = Repo(d)
            r.commit(ME, {'db/dump.sql': 'INSERT INTO t VALUES (1);\n' * 60, 'app.py': lines('me', 5)})
            count, units = self.check(r)
            self.assertEqual((count['own'], count['files']), (5, 1))
            self.assertEqual([u['path'] for u in units], ['app.py'])

    def test_generated_file_changed_again_is_still_excluded(self):  # 두 번 이상 바뀐 파일(blame 길)도 같고, blame까지 가지 않는다
        with tempfile.TemporaryDirectory() as d:
            r = Repo(d)
            r.commit(ME, {'db/dump.sql': 'INSERT INTO t VALUES (1);\n' * 60, 'app.py': lines('me', 5)})
            r.commit(ME, {'db/dump.sql': 'INSERT INTO t VALUES (2);\n' * 70})
            with mock.patch.object(subprocess, 'run', wraps=subprocess.run) as run:
                count, units = extract.blame(r.path, r.head(), EMAILS, NAMES)
            self.assertEqual((count['own'], count['files']), (5, 1))
            self.assertEqual([u['path'] for u in units], ['app.py'])
            self.assertEqual([c.args[0][-1] for c in run.call_args_list if 'blame' in c.args[0]], [])
            self.assertEqual(count, blame_reference(r.path, r.head(), EMAILS, NAMES)[0])

    def test_generated_verdict_looks_only_at_the_first_64kb(self):  # 앞 64KB가 긴 줄이면, 뒤에 짧은 줄이 많아 파일 전체 평균이 짧아도 생성 파일이다
        with tempfile.TemporaryDirectory() as d:
            r = Repo(d)
            body = (b'x' * 399 + b'\n') * 200 + b'\n' * 50_000  # 앞 64KB는 평균 약 400바이트, 파일 전체는 5만 줄이라 평균 1.3바이트
            self.assertGreater(len(body), paths.HEAD_BYTES)
            r.commit(ME, {'data/big.json': body, 'app.py': lines('me', 5)})
            count, units = self.check(r)
            self.assertEqual((count['own'], count['files']), (5, 1))
            self.assertEqual([u['path'] for u in units], ['app.py'])

    def test_binary_file_with_nul_is_not_counted_as_lines(self):  # blame 길(두 번 바뀐 파일)과 빠른 길 모두
        with tempfile.TemporaryDirectory() as d:
            r = Repo(d)
            r.commit(ME, {'out.txt': 'hello\nworld\n'.encode('utf-16'), 'v.dat': b'\x00\x01\nab\n', 'app.py': lines('me', 5)})
            r.commit(ME, {'v.dat': b'\x00\x02\nab\n'})
