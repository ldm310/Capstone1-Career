class FakeApiBehavior(unittest.TestCase):
    """testkit.FakeApi는 extract.Api의 get·pages와 같은 모양으로 답한다: 값이 예외면 던지고, 없는 경로는 404, 호출은 기록한다."""
    def test_get_returns_value_and_records_calls(self):
        api = FakeApi({'/users/a': {'id': 1}, '/empty': None})
        self.assertEqual(api.get('/users/a'), ({'id': 1}, {}, 200))
        self.assertEqual(api.get('/empty', {'x': 1}, ok=(200, 404)), (None, {}, 200))
        self.assertEqual((api.calls, api.seen, api.remaining), (2, [('/users/a', None), ('/empty', {'x': 1})], None))

    def test_missing_route_is_404_like_the_real_api(self):
        api = FakeApi({})
        self.assertEqual(api.get('/repos/o/r', ok=(200, 404)), (None, {}, 404))
        with self.assertRaisesRegex(extract.StopCheck, 'GET /repos/o/r → HTTP 404'): api.get('/repos/o/r')
        with self.assertRaisesRegex(extract.StopCheck, 'GET /repos/o/r/commits → HTTP 404'): list(api.pages('/repos/o/r/commits', {}))
        self.assertEqual(api.calls, 3)

    def test_exception_values_are_raised(self):
        api = FakeApi({'/a': extract.StopCheck('API 한도 소진'), '/b': ValueError('boom')})
        with self.assertRaises(extract.StopCheck): api.get('/a')
        with self.assertRaises(ValueError): list(api.pages('/b', {}))
        self.assertEqual(api.calls, 2)  # 던진 요청도 호출로 센다

    def test_pages_yields_the_items_of_a_list(self):
        api = FakeApi({'/l': [{'n': 1}, {'n': 2}], '/none': None, '/empty': []})
        self.assertEqual(list(api.pages('/l', {'per_page': 100})), [{'n': 1}, {'n': 2}])
        self.assertEqual(list(api.pages('/none', {})) + list(api.pages('/empty', {}, max_pages=3)), [])
        self.assertEqual((api.calls, api.seen[0]), (3, ('/l', {'per_page': 100})))


